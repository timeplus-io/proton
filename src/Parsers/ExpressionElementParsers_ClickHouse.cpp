String ParserFunction::functionNameFromCamelToSnake(const String & name)
{
    if (auto it = function_map.find(name); it != function_map.end())
        return it->second;

    String lower_name = Poco::toLower(name);
    if (auto it = case_insensitive_function_map.find(lower_name); it != case_insensitive_function_map.end())
        return it->second;

    return name;
}

